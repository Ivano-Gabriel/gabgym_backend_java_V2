-- Banco novo e exclusivo do GABGYM. Flyway cria o schema privado gabgym.
-- Não aplicar sobre um banco legado MySQL sem exportação e plano de migração.

CREATE TABLE gabgym.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(80) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(30) DEFAULT 'ALUNO',
    active boolean DEFAULT true,
    session_version integer DEFAULT 0,
    last_totp_counter bigint DEFAULT -1,
    name varchar(255),
    age integer,
    weight double precision,
    height double precision,
    gender varchar(255),
    objective varchar(255),
    activity_level varchar(255)
);

CREATE TABLE gabgym.muscle_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE gabgym.exercises (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    description text,
    local_video_path varchar(255),
    image_path varchar(255),
    muscle_group_id bigint NOT NULL REFERENCES gabgym.muscle_groups(id)
);

CREATE TABLE gabgym.food_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE gabgym.food_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    unit varchar(50),
    serving_desc varchar(100),
    calories double precision NOT NULL DEFAULT 0,
    protein double precision NOT NULL DEFAULT 0,
    carbs double precision NOT NULL DEFAULT 0,
    fat double precision NOT NULL DEFAULT 0,
    image_path varchar(255),
    category_id bigint NOT NULL REFERENCES gabgym.food_categories(id)
);

CREATE TABLE gabgym.metas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES gabgym.users(id),
    titulo varchar(200) NOT NULL,
    descricao text,
    status varchar(20) NOT NULL DEFAULT 'ATIVA'
);

CREATE TABLE gabgym.diary_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES gabgym.users(id),
    type varchar(255),
    name varchar(255),
    calories integer,
    protein double precision,
    carbs double precision,
    fat double precision,
    volume integer,
    log_date date,
    "timestamp" bigint
);

CREATE TABLE gabgym.daily_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES gabgym.users(id),
    date date,
    calories_consumed integer NOT NULL DEFAULT 0,
    protein_consumed integer NOT NULL DEFAULT 0,
    carbs_consumed integer NOT NULL DEFAULT 0,
    fat_consumed integer NOT NULL DEFAULT 0,
    water_ml integer NOT NULL DEFAULT 0,
    sleep_hours double precision NOT NULL DEFAULT 0
);

CREATE INDEX idx_metas_user_id ON gabgym.metas(user_id);
CREATE INDEX idx_diary_logs_user_date ON gabgym.diary_logs(user_id, log_date);
CREATE INDEX idx_daily_logs_user_date ON gabgym.daily_logs(user_id, date);
CREATE INDEX idx_exercises_muscle_group ON gabgym.exercises(muscle_group_id);
CREATE INDEX idx_food_items_category ON gabgym.food_items(category_id);

-- Schema gabgym pre-provisionado por admin do banco com acesso exclusivo ao app role.
-- Não conceder privilégios de schema ou tabelas aos papéis anon/authenticated.
