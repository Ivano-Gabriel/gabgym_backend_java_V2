-- Portal de acompanhamento: nunca amplia as permissões do diário existente.
-- Uma solicitação por aluno, com revogação a qualquer momento.
CREATE TABLE gabgym.coach_relationships (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id bigint NOT NULL UNIQUE REFERENCES gabgym.users(id),
 coach_id bigint NOT NULL REFERENCES gabgym.users(id),
 status varchar(20) NOT NULL DEFAULT 'PENDING',
 created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT coach_relationship_status CHECK (status IN ('PENDING','ACTIVE','REJECTED','REVOKED')),
 CONSTRAINT coach_relationship_not_self CHECK (coach_id <> student_id)
);
CREATE INDEX idx_coach_relationship_coach_status ON gabgym.coach_relationships(coach_id,status);

CREATE TABLE gabgym.coach_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 relationship_id bigint NOT NULL REFERENCES gabgym.coach_relationships(id),
 author_id bigint NOT NULL REFERENCES gabgym.users(id),
 kind varchar(16) NOT NULL,
 content varchar(2000) NOT NULL,
 status varchar(16) NOT NULL DEFAULT 'NONE',
 created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT coach_entry_kind CHECK (kind IN ('MESSAGE','ALERT','PLAN','NOTE')),
 CONSTRAINT coach_entry_status CHECK (status IN ('NONE','PENDING','APPROVED','REJECTED'))
);
CREATE INDEX idx_coach_entries_rel_created ON gabgym.coach_entries(relationship_id,created_at DESC);
